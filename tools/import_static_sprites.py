"""Import artwork only; preserve source pixels and credit, never execute pack scripts."""
from pathlib import Path
from PIL import Image
import shutil, json, sys

root = Path('1025Dex/sprites')
source = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('.work/gen9-static-3.3.8')
folders = {'Front':'front', 'Front shiny':'front_shiny', 'Back':'back', 'Back shiny':'back_shiny'}
index, sizes = {}, {}
for original, target in folders.items():
    dest = root / 'assets/static' / target
    dest.mkdir(parents=True, exist_ok=True)
    entries = {}
    for f in sorted((source/'Graphics/Pokemon'/original).iterdir()):
        if f.suffix.lower() != '.png': continue
        im = Image.open(f)
        assert im.width == im.height, f
        entries[f.stem] = True
        sizes[im.size] = sizes.get(im.size, 0) + 1
        shutil.copyfile(f, dest/(f.stem+'.png'))
    index[target] = entries

def quote(s): return json.dumps(s, ensure_ascii=True)
lines = ['-- Gen 9 Resource Pack v3.3.8 artwork inventory. Generated by tools/import_static_sprites.py.', 'return {', '  files = {']
for folder, entries in index.items():
    lines.append('    '+folder+' = {')
    lines.extend('      ['+quote(s)+'] = true,' for s in entries)
    lines.append('    },')
lines += ['  },', '  aliases = {', '    BASCULEGION_1 = "BASCULEGION_female",', '    BASCULIN_3 = "BASCULIN_2",', '    EEVEE_1 = "EEVEE",', '    EEVEE_1_female = "EEVEE_female",', '  },', '}']
(root/'data/static_data.lua').write_text('\n'.join(lines)+'\n', encoding='utf-8')

metrics = {}
for name in ['pokemon_metrics.txt', 'pokemon_metrics_Gen_9_Pack.txt']:
    stem = None
    for line in (source/'PBS'/name).read_text(encoding='utf-8-sig').splitlines():
        if line.startswith('['):
            stem = line.strip('[]').replace(',', '_')
            metrics.setdefault(stem, {})
        elif stem and '=' in line:
            key, value = map(str.strip, line.split('=',1))
            if key in ['FrontSprite','BackSprite']:
                x,y = map(int,value.split(','))
                metrics[stem].update(dict(zip(['fx','fy'] if key=='FrontSprite' else ['bx','by'], [x,y])))
            elif key in ['ShadowX', 'ShadowSize']:
                metrics[stem]['sx' if key=='ShadowX' else 'ss'] = int(value)
lines = ['-- Alignment metadata from the supplied static pack, separate from animated DBK offsets.', 'return {']
for stem, values in sorted(metrics.items()):
    lines.append('  ['+quote(stem)+'] = { '+', '.join(k+'='+str(v) for k,v in values.items())+' },')
lines += ['}']
(root/'data/static_metrics.lua').write_text('\n'.join(lines)+'\n', encoding='utf-8')
shutil.copyfile(source/'Credits.txt', root/'assets/static/GEN9-PACK-CREDITS.txt')
print('Imported', sum(map(len,index.values())), 'unchanged PNG files:',sizes)
